#include <keystone/keystone.h>
#include <memory>
#include <sstream>
#include <string>
#include <vector>

#include "common/error.h"

namespace {
cmt::Result<std::vector<unsigned char>> Assemble(ks_arch arch, int mode, const char* text, std::size_t bytes,
												 std::size_t statements)
{
	ks_engine* raw = nullptr;
	const auto opened = ks_open(arch, mode, &raw);
	if (opened != KS_ERR_OK)
	{
		return cmt::Failure(cmt::Error::Kind::Unsupported, "Keystone engine initialization failed",
							static_cast<int>(opened));
	}
	const std::unique_ptr<ks_engine, decltype(&ks_close)> engine(raw, ks_close);
	if (arch == KS_ARCH_X86)
	{
		const auto option = ks_option(raw, KS_OPT_SYNTAX, KS_OPT_SYNTAX_INTEL);
		if (option != KS_ERR_OK)
		{
			return cmt::Failure(cmt::Error::Kind::Unsupported, "Keystone Intel syntax selection failed",
								static_cast<int>(option));
		}
	}
	unsigned char* encoding = nullptr;
	std::size_t size = 0, count = 0;
	const auto result = ks_asm(raw, text, 0, &encoding, &size, &count);
	const std::unique_ptr<unsigned char, decltype(&ks_free)> owned(encoding, ks_free);
	if (result != 0)
	{
		return cmt::Failure(cmt::Error::Kind::Unsupported, "Keystone instruction assembly failed",
							static_cast<int>(ks_errno(raw)));
	}
	if (!encoding || size != bytes || count != statements)
	{
		return cmt::Failure(cmt::Error::Kind::Unsupported, "unexpected patch instruction size/count");
	}
	return std::vector<unsigned char>(encoding, encoding + size);
}

void Declaration(std::ostream& out, const char* name, const std::vector<unsigned char>& bytes)
{
	out << "inline constexpr unsigned char " << name << "[] = {";
	for (const auto byte : bytes)
	{
		out << static_cast<unsigned>(byte) << ',';
	}
	out << "};\n";
}
} // namespace

int main(int argc, char** argv)
{
	cmt::InstallFatalAllocationHandler();
	if (argc != 2)
	{
		std::fputs("usage: cmt_patch_assembler OUTPUT_HEADER\n", stderr);
		return 2;
	}
	const auto jump = Assemble(KS_ARCH_X86, KS_MODE_64, "jmp qword ptr [rip]", 6, 1);
	const auto inline_limit = Assemble(KS_ARCH_X86, KS_MODE_64, "movabs rax, 0x1122334455667788; nop", 11, 2);
	const auto trap = Assemble(KS_ARCH_X86, KS_MODE_64, "int3", 1, 1);
	const auto branch = Assemble(KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN, "ldr x16, #8; br x16", 8, 2);
	for (const auto* result : {&jump, &trap, &branch, &inline_limit})
	{
		if (!*result)
		{
			std::fprintf(stderr, "Keystone patch assembly: %s\n", result->error().Message());
			return 1;
		}
	}
	if (std::string(argv[1]) == "--self-test")
	{
		const auto bad_x86 = Assemble(KS_ARCH_X86, KS_MODE_64, "not_an_instruction", 1, 1);
		const auto bad_a64 = Assemble(KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN, "not_an_instruction", 4, 1);
		const auto bad_arch = Assemble(KS_ARCH_MAX, KS_MODE_64, "int3", 1, 1);
		const auto bad_size = Assemble(KS_ARCH_X86, KS_MODE_64, "int3", 2, 1);
		return bad_x86 || bad_a64 || bad_arch || bad_size ? 1 : 0;
	}
	std::ostringstream text;
	text << "// Generated by cmt_patch_assembler with Keystone; instructions only, no address literals.\n"
			"#pragma once\nnamespace cmt::patch::instructions {\n";
	Declaration(text, "kX86Jump", *jump);
	Declaration(text, "kX86Trap", *trap);
	Declaration(text, "kX86InlineLimit", *inline_limit);
	Declaration(text, "kA64Branch", *branch);
	text << "}\n";
	const auto content = text.str();
	std::ifstream previous(argv[1], std::ios::binary);
	if (std::string(std::istreambuf_iterator<char>(previous), {}) == content)
	{
		return 0;
	}
	const auto temporary = std::string(argv[1]) + ".tmp";
	std::ofstream output(temporary, std::ios::binary | std::ios::trunc);
	output << content;
	output.flush();
	if (!output)
	{
		std::fputs("Cannot write patch instruction header\n", stderr);
		return 1;
	}
	output.close();
	if (!output)
	{
		std::fputs("Cannot close patch instruction header\n", stderr);
		return 1;
	}
	std::error_code error;
	std::filesystem::rename(temporary, argv[1], error);
	if (error)
	{
		std::fprintf(stderr, "Cannot publish patch instruction header: %s\n", error.message().c_str());
		return 1;
	}
	return 0;
}
